/// <summary>
/// The chunk-set side the personal-data lifecycle needs (processing design §9.5; engine design §14 rules 2–3). The SQL
/// implementation is the index writer's (item 9): one fenced transaction per swap.
/// </summary>
public interface IChunkSetStore
{
    /// <summary>Inserts the set as <c>writing</c> with its chunks invisible (<c>DeletedAt</c> set).</summary>
    Task InsertWritingAsync(ChunkSetRecord set, IReadOnlyList<ChunkRecord> chunks, CancellationToken cancellationToken);

    Task<ChunkSetRecord?> GetAsync(Guid chunkSetId, CancellationToken cancellationToken);

    /// <summary>The set the document's <c>LiveChunkSetId</c> points to (<c>live</c> or <c>held</c>), or null.</summary>
    Task<ChunkSetRecord?> GetCurrentAsync(Guid documentId, CancellationToken cancellationToken);

    /// <summary>
    /// The swap: <c>LiveChunkSetId</c> → the set, which becomes <paramref name="state"/> (<c>live</c> with its chunks'
    /// <c>DeletedAt</c> cleared, or <c>held</c> with them kept deleted); the previous set → <c>superseded</c> with its chunks deleted.
    /// </summary>
    Task SwapAsync(Guid chunkSetId, string state, DateTimeOffset now, CancellationToken cancellationToken);

    /// <summary>Sets <c>live</c> or <c>held</c> on the current set without a new swap (release after a clearance, sweep).</summary>
    Task SetStateAsync(Guid chunkSetId, string state, DateTimeOffset now, CancellationToken cancellationToken);

    /// <summary>Rewrites the set's personal-data state (the sweep's re-run of <c>personal-data</c> for a <c>pending</c> set).</summary>
    Task UpdatePiiAsync(Guid chunkSetId, PiiCounts counts, bool flagged, CancellationToken cancellationToken);

    /// <summary><c>PiiFlaggedAt</c> = <paramref name="at"/> unless the set was flagged before (the first flag time is kept, #175).</summary>
    Task MarkFlaggedAsync(Guid chunkSetId, DateTimeOffset at, CancellationToken cancellationToken);

    Task<PiiClearance?> GetClearanceAsync(Guid documentId, CancellationToken cancellationToken);

    Task SetClearanceAsync(Guid documentId, PiiClearance clearance, CancellationToken cancellationToken);

    /// <summary>Current sets whose names are still unchecked (<c>PiiCounts.ner = pending</c>), for the nightly sweep.</summary>
    Task<IReadOnlyList<ChunkSetRecord>> PendingNerAsync(int limit, CancellationToken cancellationToken);

    /// <summary>The chunks of a set in ordinal order.</summary>
    Task<IReadOnlyList<ChunkRecord>> ChunksAsync(Guid chunkSetId, CancellationToken cancellationToken);
}
