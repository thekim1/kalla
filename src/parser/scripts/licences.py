def licence_of(dist: metadata.Distribution) -> str:
    """The SPDX expression, else the licence classifiers, else a one-line `License` field."""
    meta = dist.metadata
    if expression := meta.get("License-Expression"):
        return expression.strip()
    classifiers = [c.split(" :: ")[-1] for c in meta.get_all("Classifier") or [] if c.startswith("License ::")]
    if classifiers:
        return " / ".join(classifiers)
    field = (meta.get("License") or "").strip()
    if field and "\n" not in field and len(field) <= 80:
        return field
    return "see the licence files"


def licence_files(dist: metadata.Distribution) -> str:
    files = dist.metadata.get_all("License-File") or []
    return ", ".join(f"`{name}`" for name in files) or "-"


def normalise(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def runtime_names(requirements: Path) -> set[str]:
    """Package names of a `uv export` requirements file."""
    names = set()
    for line in requirements.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if line and not line.startswith(("#", "-")):
            names.add(normalise(re.split(r"[=<>!~; \[]", line, maxsplit=1)[0]))
    return names


def python_table(runtime: set[str]) -> list[str]:
    dists = {normalise(d.metadata["Name"]): d for d in metadata.distributions()}
    lines = [
        "## Python packages (`/opt/venv`)",
        "",
        "Image `runtime` is the parser image; `test` is the test image only (the dev group).",
        "",
        "| Package | Version | Licence | Licence files | Image |",
        "|---|---|---|---|---|",
    ]
    for name in sorted(dists):
        dist = dists[name]
        image = "runtime" if name in runtime else "test"
        cell = licence_of(dist).replace("|", "\\|")
        lines.append(f"| {name} | {dist.version} | {cell} | {licence_files(dist)} | {image} |")
    return lines


def model_table(manifest: Path) -> list[str]:
    models = json.loads(manifest.read_text(encoding="utf-8"))["models"]
    lines = [
        "## Models (`/opt/models`)",
        "",
        "| Model | Repository @ revision | Licence | Licence text | Notes |",
        "|---|---|---|---|---|",
    ]
    for model in models:
        lines.append(
            f"| {model['name']} | `{model['repository']}@{model['revision']}` | {model['licence']} "
            f"| `/opt/models/{model['dir']}/LICENSE` | {MODEL_NOTES[model['name']]} |"
        )
    return lines


def debian_packages(status: Path) -> list[tuple[str, str]]:
    packages = []
    for stanza in status.read_text(encoding="utf-8").split("\n\n"):
        fields = dict(re.findall(r"^([A-Za-z-]+): (.*)$", stanza, flags=re.MULTILINE))
        if fields.get("Status", "").endswith(" installed"):
            packages.append((fields["Package"], fields["Version"]))
    return sorted(packages)


